def icon(name: str, size: int = 18, color: str = "currentColor", cls: str = "") -> str:
    """
    Return an inline SVG icon from the Lucide icon set.

    Args:
        name:  Icon name (e.g. "house", "file-text", "pill")
        size:  Icon size in pixels (default 18)
        color: Stroke color (default "currentColor")
        cls:   Optional CSS class name to add to the SVG element

    Returns:
        HTML string containing the SVG icon, safe for st.markdown(unsafe_allow_html=True)
    """
    path_data = _ICON_PATHS.get(name)
    if not path_data:
        # Fallback: return empty span to avoid breaking the UI
        return f'<span style="display:inline-block;width:{size}px;height:{size}px;"></span>'

    class_attr = f' class="{cls}"' if cls else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round"{class_attr} '
        f'style="display:inline-block;vertical-align:middle;flex-shrink:0;">'
        f'{path_data}</svg>'
    )


def nav_icon(name: str, label: str, color: str = "#475569") -> str:
    """
    Return an icon + label combination suitable for sidebar navigation buttons.
    Since Streamlit buttons only accept text, this returns the label with icon prefix
    for use in st.button labels. For HTML contexts, returns icon + label HTML.

    Args:
        name:  Icon name
        label: Text label
        color: Icon color

    Returns:
        Plain text label (Streamlit buttons don't support HTML in labels)
    """
    return label


def icon_label(name: str, label: str, size: int = 16, color: str = "#475569", gap: int = 8) -> str:
    """
    Return an inline HTML fragment: SVG icon followed by a text label.
    Useful for section headers, metric labels, etc.

    Args:
        name:  Icon name
        label: Text label
        size:  Icon size in pixels
        color: Icon stroke color
        gap:   Gap between icon and label in pixels

    Returns:
        HTML string with icon and label
    """
    return (
        f'<span style="display:inline-flex;align-items:center;gap:{gap}px;">'
        f'{icon(name, size=size, color=color)}'
        f'<span>{label}</span>'
        f'</span>'
    )


