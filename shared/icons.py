def doc_type_icon(doc_type: str, size: int = 20) -> str:
    """Return the appropriate icon HTML for a document type."""
    icon_name, bg_color, fg_color = DOC_TYPE_ICONS.get(
        doc_type, ("file-text", "#F1F5F9", "#64748B")
    )
    return icon(icon_name, size=size, color=fg_color)


def doc_type_icon_circle(doc_type: str, size: int = 42) -> str:
    """Return a circular container with the document type icon inside."""
    icon_name, bg_color, fg_color = DOC_TYPE_ICONS.get(
        doc_type, ("file-text", "#F1F5F9", "#64748B")
    )
    icon_size = max(16, size - 18)
    return (
        f'<div style="width:{size}px;height:{size}px;border-radius:50%;'
        f'background:{bg_color};display:flex;align-items:center;'
        f'justify-content:center;flex-shrink:0;">'
        f'{icon(icon_name, size=icon_size, color=fg_color)}'
        f'</div>'
    )


